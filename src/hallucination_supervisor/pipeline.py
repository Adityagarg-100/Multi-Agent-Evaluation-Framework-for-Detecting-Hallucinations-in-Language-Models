# pipeline.py
"""
Central orchestrator for the Multi-Agent LLM Hallucination Supervisor.

Chains the full verification pipeline in strict chronological order:

    BaseDraftGenerator -> ClaimExtractor -> EvidenceInvestigator
        -> NLIVerifier (per claim) -> ReportCalibrator

Every stage is timed and logged so that runtime bottlenecks and agent
handoffs are fully observable in production.

Exposes two public entry points:
    - `run_verification`: returns just the aggregated `VerificationReport`
      (the common case).
    - `run_verification_detailed`: returns a `PipelineRunResult` bundling
      the draft, extracted claims, retrieved evidence, per-claim
      verdicts, AND the final report — for callers (dashboards, eval
      harnesses, CLIs) that need claim-level detail beyond the aggregate
      score.
"""

from __future__ import annotations

import asyncio
import logging
import time
from typing import List, Optional

from pydantic import BaseModel, ConfigDict

from .agents.base_generator import BaseDraftGenerator, DraftGenerationError
from .agents.calibrator import CalibrationError, ReportCalibrator
from .agents.deconstructor import ClaimExtractor, ExtractionError
from .agents.investigator import EvidenceInvestigator, InvestigationError
from .agents.judge import JudgmentError, NLIVerifier
from .schemas import AtomicClaim, ClaimEvidence, ClaimVerdict, VerificationReport

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)-8s | %(name)s | %(message)s",
)
logger = logging.getLogger(__name__)


class PipelineError(Exception):
    """
    Raised when any stage of the `SupervisorPipeline` fails
    catastrophically and cannot produce a `VerificationReport`.

    The original stage-specific exception (`DraftGenerationError`,
    `ExtractionError`, `InvestigationError`, `JudgmentError`, or
    `CalibrationError`) is always chained via `__cause__` for full
    traceback visibility.
    """


class PipelineRunResult(BaseModel):
    """
    Full bundle of every intermediate and final artifact produced by a
    single `SupervisorPipeline` run.

    `VerificationReport` (see `schemas.py`) deliberately carries only
    aggregated, cross-claim statistics — it has no `claims` or `verdicts`
    field by design, to keep the agent-to-agent data contract minimal.
    `PipelineRunResult` is the orchestrator-level, caller-facing object
    for use cases that need the full per-claim trail (dashboards, eval
    notebooks, debugging) without reaching into `SupervisorPipeline`'s
    private `_stage_*` methods.

    Attributes:
        draft: The raw draft text generated by `BaseDraftGenerator`.
        claims: The list of `AtomicClaim` objects extracted from `draft`.
            Empty if the draft contained no verifiable factual claims.
        evidence: The list of `ClaimEvidence` bundles retrieved for each
            claim in `claims`, in the same order. Empty if `claims` is
            empty.
        verdicts: The list of `ClaimVerdict` objects produced by the
            judge for each claim in `claims`, in the same order. Empty
            if `claims` is empty.
        report: The final, aggregated `VerificationReport`.
    """

    model_config = ConfigDict(arbitrary_types_allowed=False, extra="forbid")

    draft: str
    claims: List[AtomicClaim]
    evidence: List[ClaimEvidence]
    verdicts: List[ClaimVerdict]
    report: VerificationReport

    def verdict_for(self, claim_id: str) -> Optional[ClaimVerdict]:
        """
        Look up the `ClaimVerdict` corresponding to a given `claim_id`.

        Args:
            claim_id: The `claim_id` of the `AtomicClaim` to look up.

        Returns:
            The matching `ClaimVerdict`, or `None` if no verdict exists
            for the given `claim_id` (e.g., an invalid or stale ID).
        """
        for verdict in self.verdicts:
            if verdict.claim_id == claim_id:
                return verdict
        return None


class SupervisorPipeline:
    """
    Orchestrates the end-to-end hallucination detection pipeline.

    Instantiates and chains each agent in strict chronological order,
    logging elapsed wall-clock time at every handoff so that per-stage
    latency is fully traceable in production logs.

    Attributes:
        generator: The `BaseDraftGenerator` producing the candidate draft.
        extractor: The `ClaimExtractor` decomposing the draft into claims.
        investigator: The `EvidenceInvestigator` retrieving evidence per
            claim.
        judge: The `NLIVerifier` adjudicating each claim against its
            evidence.
        calibrator: The `ReportCalibrator` aggregating verdicts into a
            final report.
    """

    def __init__(
        self,
        generator: Optional[BaseDraftGenerator] = None,
        extractor: Optional[ClaimExtractor] = None,
        investigator: Optional[EvidenceInvestigator] = None,
        judge: Optional[NLIVerifier] = None,
        calibrator: Optional[ReportCalibrator] = None,
    ) -> None:
        """
        Initialize the pipeline, constructing default agent instances for
        any component not explicitly supplied (dependency injection point
        for testing/mocking).

        Args:
            generator: Optional pre-constructed `BaseDraftGenerator`.
            extractor: Optional pre-constructed `ClaimExtractor`.
            investigator: Optional pre-constructed `EvidenceInvestigator`.
            judge: Optional pre-constructed `NLIVerifier`.
            calibrator: Optional pre-constructed `ReportCalibrator`.

        Raises:
            PipelineError: If any default agent fails to construct (e.g.,
                due to missing required packages or misconfiguration).
        """
        try:
            self.generator: BaseDraftGenerator = generator or BaseDraftGenerator()
            self.extractor: ClaimExtractor = extractor or ClaimExtractor()
            self.investigator: EvidenceInvestigator = investigator or EvidenceInvestigator()
            self.judge: NLIVerifier = judge or NLIVerifier()
            self.calibrator: ReportCalibrator = calibrator or ReportCalibrator()
        except Exception as exc:  # noqa: BLE001
            raise PipelineError(f"Failed to initialize SupervisorPipeline agents: {exc}") from exc

        logger.info(
            "SupervisorPipeline initialized: generator=%s, extractor=%s, "
            "investigator=%s, judge=%s, calibrator=%s",
            type(self.generator).__name__,
            type(self.extractor).__name__,
            type(self.investigator).__name__,
            type(self.judge).__name__,
            type(self.calibrator).__name__,
        )

    def _stage_generate_draft(self, prompt: str) -> str:
        """
        Execute the draft-generation stage with timing and logging.

        Args:
            prompt: The user-facing prompt to generate a draft for.

        Returns:
            The generated draft text.

        Raises:
            PipelineError: If draft generation fails.
        """
        logger.info("STAGE 1/5 [BaseDraftGenerator] starting draft generation.")
        start = time.perf_counter()
        try:
            draft = self.generator.generate_draft(prompt)
        except DraftGenerationError as exc:
            raise PipelineError(f"Pipeline aborted at draft generation stage: {exc}") from exc
        elapsed = time.perf_counter() - start
        logger.info(
            "STAGE 1/5 [BaseDraftGenerator] complete in %.2fs. draft_length=%d chars.",
            elapsed,
            len(draft),
        )
        return draft

    def _stage_extract_claims(self, draft: str) -> List[AtomicClaim]:
        """
        Execute the claim-extraction stage with timing and logging.

        Args:
            draft: The generated draft text to decompose.

        Returns:
            The list of extracted `AtomicClaim` objects.

        Raises:
            PipelineError: If claim extraction fails.
        """
        logger.info("STAGE 2/5 [ClaimExtractor] starting claim decomposition.")
        start = time.perf_counter()
        try:
            claims = self.extractor.extract_claims(draft)
        except ExtractionError as exc:
            raise PipelineError(f"Pipeline aborted at claim extraction stage: {exc}") from exc
        elapsed = time.perf_counter() - start
        logger.info(
            "STAGE 2/5 [ClaimExtractor] complete in %.2fs. claims_extracted=%d.",
            elapsed,
            len(claims),
        )
        return claims

    def _stage_investigate(self, claims: List[AtomicClaim]) -> List[ClaimEvidence]:
        """
        Execute the evidence-investigation stage with timing and logging.

        Args:
            claims: The list of atomic claims to investigate.

        Returns:
            The list of `ClaimEvidence` objects, one per claim.

        Raises:
            PipelineError: If evidence investigation fails.
        """
        logger.info(
            "STAGE 3/5 [EvidenceInvestigator] starting concurrent evidence retrieval "
            "for %d claim(s).",
            len(claims),
        )
        start = time.perf_counter()
        try:
            evidence_list = asyncio.run(self.investigator.investigate(claims))
        except InvestigationError as exc:
            raise PipelineError(f"Pipeline aborted at evidence investigation stage: {exc}") from exc
        elapsed = time.perf_counter() - start
        avg_snippets = (
            sum(len(e.retrieved_context) for e in evidence_list) / len(evidence_list)
            if evidence_list
            else 0.0
        )
        logger.info(
            "STAGE 3/5 [EvidenceInvestigator] complete in %.2fs. "
            "evidence_bundles=%d, avg_snippets_per_claim=%.2f.",
            elapsed,
            len(evidence_list),
            avg_snippets,
        )
        return evidence_list

    def _stage_judge(
        self, claims: List[AtomicClaim], evidence_list: List[ClaimEvidence]
    ) -> List[ClaimVerdict]:
        """
        Execute the NLI judgment stage, sequentially adjudicating each
        claim against its evidence, with timing and logging.

        Args:
            claims: The list of atomic claims, ordered identically to
                `evidence_list`.
            evidence_list: The list of evidence bundles, one per claim.

        Returns:
            The list of `ClaimVerdict` objects, one per claim.

        Raises:
            PipelineError: If claims and evidence lists are misaligned in
                length, or if judgment fails for any claim.
        """
        if len(claims) != len(evidence_list):
            raise PipelineError(
                f"Pipeline aborted: claims/evidence length mismatch "
                f"({len(claims)} vs {len(evidence_list)})."
            )

        logger.info("STAGE 4/5 [NLIVerifier] starting adjudication of %d claim(s).", len(claims))
        start = time.perf_counter()
        verdicts: List[ClaimVerdict] = []

        for claim, evidence in zip(claims, evidence_list):
            claim_start = time.perf_counter()
            try:
                verdict = self.judge.evaluate_claim(claim, evidence)
            except JudgmentError as exc:
                raise PipelineError(
                    f"Pipeline aborted at NLI judgment stage for claim_id={claim.claim_id}: {exc}"
                ) from exc
            claim_elapsed = time.perf_counter() - claim_start
            logger.debug(
                "  Judged claim_id=%s -> status=%s (confidence=%.2f) in %.2fs.",
                claim.claim_id,
                verdict.status,
                verdict.confidence_score,
                claim_elapsed,
            )
            verdicts.append(verdict)

        elapsed = time.perf_counter() - start
        status_counts = {
            status: sum(1 for v in verdicts if v.status == status)
            for status in ("SUPPORTED", "CONTRADICTED", "UNVERIFIABLE")
        }
        logger.info(
            "STAGE 4/5 [NLIVerifier] complete in %.2fs. status_breakdown=%s.",
            elapsed,
            status_counts,
        )
        return verdicts

    def _stage_calibrate(
        self, draft: str, claims: List[AtomicClaim], verdicts: List[ClaimVerdict]
    ) -> VerificationReport:
        """
        Execute the report-calibration stage with timing and logging.

        Args:
            draft: The original generated draft text.
            claims: The full list of atomic claims extracted from the
                draft.
            verdicts: The full list of verdicts produced by the judge.

        Returns:
            The final, aggregated `VerificationReport`.

        Raises:
            PipelineError: If report calibration fails.
        """
        logger.info("STAGE 5/5 [ReportCalibrator] starting report aggregation.")
        start = time.perf_counter()
        try:
            report = self.calibrator.generate_report(
                original_draft=draft, claims=claims, verdicts=verdicts
            )
        except CalibrationError as exc:
            raise PipelineError(f"Pipeline aborted at calibration stage: {exc}") from exc
        elapsed = time.perf_counter() - start
        logger.info(
            "STAGE 5/5 [ReportCalibrator] complete in %.2fs. "
            "hallucination_percentage=%.2f%%, supported_ratio=%.2f, spans_flagged=%d.",
            elapsed,
            report.hallucination_percentage,
            report.supported_ratio,
            len(report.hallucinated_spans),
        )
        return report

    def _execute(self, prompt: str) -> PipelineRunResult:
        """
        Run the full end-to-end pipeline and return every intermediate
        and final artifact.

        This is the single internal implementation shared by both public
        entry points (`run_verification` and `run_verification_detailed`)
        so the five-stage execution logic is defined exactly once.

        Args:
            prompt: The user-facing prompt to generate and verify a draft
                response for.

        Returns:
            A `PipelineRunResult` bundling the draft, claims, evidence,
            verdicts, and final report. If no claims are extracted (e.g.,
            a purely conversational draft), `claims`, `evidence`, and
            `verdicts` are all empty lists and `report` reflects a
            zero-claim run.

        Raises:
            PipelineError: If `prompt` is empty/whitespace-only, or if any
                pipeline stage fails irrecoverably. The original
                stage-specific exception is always chained via
                `__cause__`.
        """
        cleaned_prompt = prompt.strip()
        if not cleaned_prompt:
            raise PipelineError("Pipeline run called with an empty prompt.")

        pipeline_start = time.perf_counter()
        logger.info("=" * 72)
        logger.info("SupervisorPipeline run started. prompt_length=%d chars.", len(cleaned_prompt))

        draft = self._stage_generate_draft(cleaned_prompt)
        claims = self._stage_extract_claims(draft)

        if not claims:
            logger.info(
                "No atomic claims extracted from draft; skipping investigation and "
                "judgment stages, emitting zero-claim report."
            )
            report = self._stage_calibrate(draft, claims=[], verdicts=[])
            total_elapsed = time.perf_counter() - pipeline_start
            logger.info(
                "SupervisorPipeline run complete in %.2fs (no claims to verify).",
                total_elapsed,
            )
            logger.info("=" * 72)
            return PipelineRunResult(
                draft=draft,
                claims=[],
                evidence=[],
                verdicts=[],
                report=report,
            )

        evidence_list = self._stage_investigate(claims)
        verdicts = self._stage_judge(claims, evidence_list)
        report = self._stage_calibrate(draft, claims, verdicts)

        total_elapsed = time.perf_counter() - pipeline_start
        logger.info(
            "SupervisorPipeline run complete in %.2fs. "
            "total_claims=%d, hallucination_percentage=%.2f%%.",
            total_elapsed,
            report.total_claims,
            report.hallucination_percentage,
        )
        logger.info("=" * 72)

        return PipelineRunResult(
            draft=draft,
            claims=claims,
            evidence=evidence_list,
            verdicts=verdicts,
            report=report,
        )

    def run_verification(self, prompt: str) -> VerificationReport:
        """
        Execute the full end-to-end hallucination verification pipeline
        for a given prompt, returning only the aggregated report.

        This is the primary entry point for callers who only need the
        summary score (`hallucination_percentage`, `supported_ratio`,
        `hallucinated_spans`) and don't need per-claim verdict detail.
        Use `run_verification_detailed` instead if you need the full
        claims/evidence/verdicts trail.

        Args:
            prompt: The user-facing prompt to generate and verify a draft
                response for.

        Returns:
            The final `VerificationReport` for the generated draft.

        Raises:
            PipelineError: If `prompt` is empty/whitespace-only, or if any
                pipeline stage fails irrecoverably.
        """
        return self._execute(prompt).report

    def run_verification_detailed(self, prompt: str) -> PipelineRunResult:
        """
        Execute the full end-to-end hallucination verification pipeline
        for a given prompt, returning every intermediate artifact.

        Use this entry point when you need per-claim detail — e.g., to
        render a claim-by-claim verdict table, build a dashboard, or
        debug why a particular claim was flagged — rather than reaching
        into `SupervisorPipeline`'s private `_stage_*` methods.

        Args:
            prompt: The user-facing prompt to generate and verify a draft
                response for.

        Returns:
            A `PipelineRunResult` containing the draft, extracted claims,
            retrieved evidence, per-claim verdicts, and the final
            aggregated `VerificationReport`.

        Raises:
            PipelineError: If `prompt` is empty/whitespace-only, or if any
                pipeline stage fails irrecoverably.
        """
        return self._execute(prompt)